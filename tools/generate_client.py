"""Generate the internal API client from contracts/internal.json.

openapi-python-client writes the client and its models into gmshield_worker/backend/generated/,
which is git-ignored and rebuilt by the Dockerfile and before every local test run. Nothing in it
is edited by hand.

Run from the repository root:  uv run python tools/generate_client.py
"""

from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts" / "internal.json"
CONFIG = ROOT / "tools" / "openapi-python-client.yaml"
TARGET = ROOT / "gmshield_worker" / "backend" / "generated"


def main() -> int:
    generator = shutil.which("openapi-python-client")
    if generator is None:
        print("openapi-python-client is not installed: run `uv sync --locked` first.", file=sys.stderr)
        return 1
    if TARGET.exists():
        shutil.rmtree(TARGET)
    completed = subprocess.run(
        [
            generator,
            "generate",
            "--path",
            str(CONTRACT),
            "--config",
            str(CONFIG),
            "--meta",
            "none",
            "--output-path",
            str(TARGET),
            "--overwrite",
        ],
        cwd=ROOT,
        check=False,
    )
    if completed.returncode != 0:
        return completed.returncode
    # Records which contract the client came from, so that a test catches a stale client.
    document = CONTRACT.read_bytes()
    version = json.loads(document)["info"]["version"]
    (TARGET / "_contract.py").write_text(
        '"""Generated by tools/generate_client.py: the contract this client was generated from."""\n\n'
        f"CONTRACT_VERSION = {version!r}\n"
        f"CONTRACT_SHA256 = {hashlib.sha256(document).hexdigest()!r}\n",
        encoding="utf-8",
    )
    print(f"Generated {TARGET.relative_to(ROOT)} from {CONTRACT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
